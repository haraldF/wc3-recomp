// Usage: node src/cli.ts <command> [--iso file] [--out dir] [--seconds n]
//   --iso        the CD image holding WC3.EXE (default ../game3/DATA.DAT, GOG's)
//   unpack       WC3.EXE from the CD image, its P3 load image to out/image.bin, its start to out/p3.json
//   decompile    unpack, import into a Ghidra project (out/ghidra) and analyze
//   recomp       translate the analyzed program to C++ (out/recomp/) and build out/bin/wc3
//   build        only (re)build out/bin/wc3 from out/recomp/ and runtime/ (CMake, in out/build/)
//   web          build the web page in out/web/ from out/recomp/ and runtime/ (Emscripten, in out/build-web/)
//   discover     run out/bin/wc3 (each run for --seconds, default 60; WC_KEYS etc. from the environment);
//                when it reaches code that wasn't recompiled (reached only through pointers in data),
//                add that entry point to entries.txt, recompile, repeat;
//                when it calls code the game loaded at runtime (drivers), capture it to out/loaded/
//                and recompile that too
//   play         the same in the window, for playing: after each recompile the game starts again
//                (arguments after "play" go to the game)

import { spawn, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import { findGhidra, runHeadless } from "./ghidra.ts";
import { parseP3, readIsoFile } from "./p3.ts";

const root = path.resolve(import.meta.dirname, "..");
const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: {
    iso: { type: "string", default: path.resolve(root, "../game3/DATA.DAT") },
    out: { type: "string", default: path.join(root, "out") },
    seconds: { type: "string", default: "60" },
  },
});

// Wing Commander III: Heart of the Tiger (GOG): WC3.EXE on the CD image, MetaWare High C, Phar Lap P3.
// Only this release (by SHA-256): another one differs in code and data, so the addresses in the
// entries file and the runtime would be wrong. CYCLES: the default speed (instructions per ms).
const EXE = "WC3.EXE";
const SHA256 = "a53c6a99917474c9be429485f745d13037bab2449680319a61e2fa054ec9b0df";
const CYCLES = 100000; // GOG's DOSBox: cycles=max; to be tuned

const isoPath = path.resolve(values.iso);
const command = positionals[0];
const out = path.resolve(values.out);
const p3Path = path.join(out, "p3.json"); // the program's start and memory
const flatImage = path.join(out, "image.bin");
const projectDir = path.join(out, "ghidra");
const scriptPath = path.join(root, "ghidra_scripts");
const projectName = "WC";
const recompDir = path.join(out, "recomp");
const entriesFile = path.join(root, "entries.txt"); // kept in the repository
const wcExe = path.join(out, "bin", "wc3");

// Code the game loads at runtime, captured from memory and recompiled at a virtual address each.
interface Driver { name: string; virt: number; file: string }
const loadedDir = path.join(out, "loaded");
const capturesDir = path.join(loadedDir, "captures");
const driversFile = path.join(loadedDir, "drivers.json");
const readDrivers = (): Driver[] => (existsSync(driversFile) ? JSON.parse(readFileSync(driversFile, "utf8")) : []);
// Which name (and so virtual address) each driver gets, by a hash of its captured bytes (kept in the
// repository: the driver entry points in entries.txt depend on it, and captures come in any order).
// Drivers with a code selector of their own are recompiled at DRIVER_VIRT + n * DRIVER_SPACING;
// those loaded into the program's memory ("flat") at the offset they were captured from, the third
// column.
const driverIdsFile = path.join(root, "drivers.txt");
const DRIVER_VIRT = 0x10000000, DRIVER_SPACING = 0x1000000; // as in runtime/wc_rt.h
const driverHash = (image: Buffer): string => createHash("sha256").update(image.subarray(0, 4096)).digest("hex").slice(0, 16);
const readDriverIds = (): { name: string; hash: string; virt?: number }[] =>
  (existsSync(driverIdsFile) ? readFileSync(driverIdsFile, "utf8").split("\n") : [])
    .map((l) => l.replace(/#.*/, "").trim().split(/\s+/))
    .filter((w) => w.length >= 2)
    .map(([name, hash, virt]) => ({ name: name!, hash: hash!, virt: virt ? parseInt(virt, 16) : undefined }));
const hex = (n: number): string => n.toString(16);

const importDriver = (d: Driver): Promise<void> =>
  runHeadless(findGhidra(), [
    projectDir, `${projectName}/loaded`,
    "-import", path.join(loadedDir, d.file), "-overwrite",
    "-loader", "BinaryLoader", "-loader-baseAddr", `0x${hex(d.virt)}`, "-processor", "x86:LE:32:default", "-cspec", "gcc",
    "-scriptPath", scriptPath, "-preScript", "WcDriverSetup.java", entriesFile,
  ]);

/** wc_drivers.cpp: the runtime's list of recompiled drivers. */
function writeDriverList(drivers: Driver[]): void {
  const lines = ["/* Generated by cli.ts: the recompiled drivers. */", '#include "wc_rt.h"', ""];
  for (const d of drivers) lines.push(`extern const wc_driver wc_drv_${d.name};`);
  const items = drivers.map((d) => `&wc_drv_${d.name}`);
  lines.push(`extern const wc_driver *const wc_drivers[${Math.max(drivers.length, 1)}] = { ${items.join(", ") || "nullptr"} };`);
  lines.push(`extern const uint32_t wc_driver_count = ${drivers.length};`, "");
  const file = path.join(recompDir, "wc_drivers.cpp");
  const text = lines.join("\n");
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
}
const gameDir = path.dirname(isoPath);

const doRecomp = async (): Promise<void> => {
  mkdirSync(recompDir, { recursive: true });
  await runHeadless(findGhidra(), [
    projectDir, projectName,
    "-process", path.basename(flatImage), "-noanalysis", "-readOnly",
    "-scriptPath", scriptPath,
    "-postScript", "WcRecomp.java", recompDir, entriesFile,
  ]);
  const drivers = readDrivers();
  // A driver is recompiled only when its bytes, its entries or the generator changed (a Ghidra run
  // per driver took most of each discover round, and new entries are mostly the program's).
  const entries = existsSync(entriesFile)
    ? readFileSync(entriesFile, "utf8").split("\n").map((l) => l.replace(/#.*/, "").trim()).filter((l) => l)
    : [];
  const generator = readFileSync(path.join(scriptPath, "WcRecomp.java"));
  for (const d of drivers) {
    const image = readFileSync(path.join(loadedDir, d.file));
    const mine = entries.filter((e) => {
      const a = parseInt(e, 16);
      return a >= d.virt && a < d.virt + image.length;
    });
    const stamp = createHash("sha256").update(image).update(generator).update(mine.join(",")).digest("hex");
    const stampFile = path.join(recompDir, `drv_${d.name}.stamp`);
    if (existsSync(path.join(recompDir, `drv_${d.name}.cpp`)) && existsSync(stampFile) &&
      readFileSync(stampFile, "utf8") === stamp) continue;
    await runHeadless(findGhidra(), [
      projectDir, `${projectName}/loaded`,
      "-process", d.file, "-noanalysis", "-readOnly",
      "-scriptPath", scriptPath,
      "-postScript", "WcRecomp.java", "driver", recompDir, d.name, entriesFile,
    ]);
    writeFileSync(stampFile, stamp);
  }
  writeDriverList(drivers);
  await doBuild();
};
/** Configure (once) and build with CMake; web: with Emscripten, into out/web. */
const cmakeBuild = async (web: boolean): Promise<void> => {
  writeProgram();
  const buildDir = path.join(out, web ? "build-web" : "build");
  const binDir = path.join(out, web ? "web" : "bin");
  if (!existsSync(path.join(buildDir, "CMakeCache.txt"))) {
    const ninja = spawnSync("ninja", ["--version"]).status === 0 ? ["-G", "Ninja"] : [];
    const args = ["-S", root, "-B", buildDir, ...ninja, `-DWC_RECOMP_DIR=${recompDir}`, `-DWC_BIN_DIR=${binDir}`];
    await (web ? exec("emcmake", ["cmake", ...args]) : exec("cmake", args));
  }
  await exec("cmake", ["--build", buildDir]);
  console.log(`built ${web ? path.join(binDir, "index.html") : wcExe}`);
};
const doBuild = (): Promise<void> => cmakeBuild(false);

/** wc_program.cpp: what the runtime needs from the program's P3 header and name. */
function writeProgram(): void {
  const h = (n: number): string => `0x${n.toString(16).padStart(4, "0")}`;
  const p = JSON.parse(readFileSync(p3Path, "utf8")) as { base: number; eip: number; esp: number; size: number; minExtra: number };
  const text = [
    "/* Generated by cli.ts: the program's start, from its P3 header. */",
    '#include "wc_rt.h"', "",
    `const struct wc_program wc_program = { "${EXE}", ${CYCLES}, ${h(p.base)}, ${h(p.eip)}, ${h(p.esp)}, ${h(p.size + p.minExtra)} };`,
    "",
  ].join("\n");
  const file = path.join(recompDir, "wc_program.cpp");
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
}

/** WC3.EXE from the CD image, its P3 load image unpacked to image.bin, the start to p3.json. */
function doUnpack(): void {
  const file = readIsoFile(isoPath, EXE);
  const sha = createHash("sha256").update(file).digest("hex");
  if (sha !== SHA256) {
    throw new Error(`${EXE} in ${isoPath} is not the expected one (SHA-256 ${sha}, expected ${SHA256}); ` +
      "this project needs the GOG release's");
  }
  const p = parseP3(file);
  mkdirSync(out, { recursive: true });
  writeFileSync(flatImage, p.image);
  writeFileSync(p3Path, JSON.stringify({ base: p.base, eip: p.eip, esp: p.esp, size: p.image.length, minExtra: p.minExtra }, null, 2));
  console.log(`${flatImage}: ${p.image.length} bytes at ${p.base.toString(16)}, entry ${p.eip.toString(16)}`);
}

async function main(): Promise<void> {
  switch (command) {
    case "unpack":
      doUnpack();
      break;
    case "decompile": {
      doUnpack();
      const p = JSON.parse(readFileSync(p3Path, "utf8")) as { base: number; eip: number };
      mkdirSync(projectDir, { recursive: true });
      await runHeadless(findGhidra(), [
        projectDir, projectName,
        "-import", flatImage, "-overwrite", "-loader", "BinaryLoader", "-loader-baseAddr", `0x${p.base.toString(16)}`,
        "-processor", "x86:LE:32:default", "-cspec", "gcc",
        "-scriptPath", scriptPath, "-preScript", "WcFlat32Setup.java", p.eip.toString(16),
        "-analysisTimeoutPerFile", "7200",
      ]);
      break;
    }
    case "recomp":
      await doRecomp();
      break;
    case "build":
      await doBuild();
      break;
    case "web":
      await cmakeBuild(true);
      break;
    case "discover":
    case "play": {
      // play: in the window, without a time limit, at the normal speed; the game starts again after each recompile
      const play = command === "play";
      mkdirSync(capturesDir, { recursive: true });
      for (let round = 1; round <= 50; round++) {
        const env = play ? { ...process.env, WC_LOADED_DIR: capturesDir }
          : { ...process.env, WC_LOADED_DIR: capturesDir, WC_HEADLESS: "1", WC_CYCLES: process.env.WC_CYCLES ?? "max" };
        const res = spawnSync(wcExe, [gameDir, ...positionals.slice(1)], {
          encoding: "utf8", timeout: play ? undefined : Number(values.seconds) * 1000, env,
          stdio: ["inherit", play ? "inherit" : "pipe", "pipe"],
        });
        if (play) process.stderr.write(res.stderr ?? "");
        const loaded = /wc: call into code loaded at runtime at [0-9a-f]+:([0-9a-f]+) \((flat|own segment), captured from offset ([0-9a-f]+)/
          .exec(res.stderr ?? "");
        const capture = /wc: saved loaded code to (.+)/.exec(res.stderr ?? "")?.[1];
        if (res.status === 5 && loaded && capture) {
          const off = parseInt(loaded[1]!, 16), flat = loaded[2] === "flat", from = parseInt(loaded[3]!, 16);
          const image = readFileSync(capture);
          const hash = driverHash(image);
          const ids = readDriverIds();
          let name = ids.find((i) => i.hash === hash)?.name;
          const known = ids.find((i) => i.hash === hash);
          const drivers = readDrivers();
          if (name && drivers.some((d) => d.name === name)) {
            console.log(`round ${round}: code at offset ${loaded[1]} looks like driver ${name}, but it wasn't recognised ` +
              "(changed in memory?):");
            console.log((res.stderr ?? "").split("\n").slice(-8).join("\n"));
            break;
          }
          if (!name) {
            let n = 0;
            while (ids.some((i) => i.name === `d${n}`)) n++;
            name = `d${n}`;
            appendFileSync(driverIdsFile, `${name} ${hash}${flat ? ` ${hex(from)}` : ""}\n`);
          }
          const virt = flat ? known?.virt ?? from : DRIVER_VIRT + Number(name.slice(1)) * DRIVER_SPACING;
          const d: Driver = { name, virt, file: `${name}.bin` };
          writeFileSync(path.join(loadedDir, d.file), image);
          writeFileSync(driversFile, JSON.stringify([...drivers, d], null, 2));
          appendFileSync(entriesFile, `${hex(flat ? off : d.virt + off)}\n`);
          console.log(`round ${round}: new code loaded at runtime (offset ${loaded[1]}), recompiling it as ${d.name}`);
          await importDriver(d);
          await doRecomp();
          continue;
        }
        const missing = /wc: missing code at ([0-9a-f]+)/.exec(res.stderr ?? "")?.[1];
        if (res.status !== 4 || !missing) {
          if (play) break;
          const timedOut = (res.error as NodeJS.ErrnoException | undefined)?.code === "ETIMEDOUT";
          console.log(`round ${round}: ` + (timedOut ? `wc3 was still running after ${values.seconds} s, no missing code so far`
            : `wc3 stopped (exit ${res.status ?? res.signal}):`));
          console.log((res.stderr ?? "").split("\n").slice(-8).join("\n"));
          break;
        }
        const known = existsSync(entriesFile) ? readFileSync(entriesFile, "utf8").split(/\s+/) : [];
        if (known.includes(missing)) {
          console.log(`round ${round}: missing code at ${missing} again; the generator could not recompile it:`);
          console.log((res.stderr ?? "").split("\n").slice(-8).join("\n"));
          break;
        }
        console.log(`round ${round}: missing code at ${missing}, adding it as an entry point`);
        appendFileSync(entriesFile, `${missing}\n`);
        await doRecomp();
      }
      break;
    }
    default:
      console.error("usage: node src/cli.ts <unpack|decompile|recomp|build|web|discover|play> [--iso file] [--out dir] [--seconds n]");
      process.exit(2);
  }
}

function exec(cmd: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: ["ignore", "inherit", "inherit"] });
    child.on("error", reject);
    child.on("exit", (code) => (code === 0 ? resolve() : reject(new Error(`${cmd} ${args.join(" ")} failed (${code})`))));
  });
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
